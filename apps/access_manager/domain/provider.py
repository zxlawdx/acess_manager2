from __future__ import annotations
from typing import Any, Protocol
from .capabilities import CapabilitySet

class DeviceProvider(Protocol):
    vendor: str
    @property
    def connected(self) -> bool: ...
    @property
    def capabilities(self) -> CapabilitySet: ...
    def connect(self, host: str, username: str, password: str, **kwargs) -> dict[str, Any]: ...
    def disconnect(self) -> None: ...
    def get_device_info(self) -> dict[str, Any]: ...
    def get_clients(self) -> list[dict[str, Any]]: ...
    def get_wifi(self) -> dict[str, Any] | list[dict[str, Any]]: ...
    def get_wan(self) -> dict[str, Any]: ...
    def get_lan(self) -> list[dict[str, Any]] | dict[str, Any]: ...
    def get_dhcp(self) -> dict[str, Any]: ...
    def get_dns(self) -> dict[str, Any]: ...
    def get_optical(self) -> dict[str, Any]: ...
    def get_traffic(self) -> dict[str, Any]: ...
    def reboot(self) -> dict[str, Any]: ...
